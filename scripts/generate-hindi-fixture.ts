import fs from "fs";
import path from "path";

const fixturesDir = path.resolve(process.cwd(), "src/fixtures");

function generateHindiPage(pageNum: number): string {
  const marker = `--- [Page ${pageNum}] ---`;
  const topics = [
    "कार्यकारी सारांश एवं परिचालन प्रदर्शन",
    "वित्तीय विवरण एवं राजस्व विश्लेषण",
    "डिजिटल परिवर्तन एवं तकनीकी अवसंरचना",
    "ग्राहक अधिग्रहण एवं बाजार हिस्सेदारी",
    "मानव संसाधन एवं संगठनात्मक विकास",
    "नियामक अनुपालन एवं जोखिम प्रबंधन",
    "सतत विकास एवं कॉर्पोरेट सामाजिक उत्तरदायित्व",
    "रणनीतिक साझेदारी एवं वैश्विक विस्तार",
  ];
  const topic = topics[(pageNum - 1) % topics.length];
  const revenue = (pageNum * 3.4 + 18.5).toFixed(1);
  const growth = ((pageNum % 6) + 16).toFixed(1);
  const margin = (65 + (pageNum % 9)).toFixed(1);
  const users = (pageNum * 2800 + 52000).toLocaleString("hi-IN");

  return `${marker}
वार्षिक कॉर्पोरेट समीक्षा एवं रणनीतिक रिपोर्ट 2026 - ${topic} (पृष्ठ ${pageNum})

१. अनुभाग अवलोकन एवं रणनीतिक प्राथमिकताएं:
वित्तीय वर्ष 2026 की इस अवधि में संस्था ने अपने प्रमुख कार्यक्षेत्रों में निरंतर प्रगति दर्ज की है। क्षेत्रीय बाजारों और संस्थागत ग्राहकों के सहयोग से परिचालन दक्षता में उल्लेखनीय सुधार हुआ है। इस खंड का कुल शुद्ध राजस्व ₹${revenue} करोड़ दर्ज किया गया, जो पिछले वर्ष की तुलना में ${growth}% की वार्षिक वृद्धि दर्शाता है। सकल लाभ मार्जिन ${margin}% पर स्थिर रहा, जो सुदृढ़ लागत प्रबंधन का प्रमाण है।

२. प्रमुख संख्यात्मक संकेतक एवं व्यावसायिक आंकड़े:
- वार्षिक आवर्ती राजस्व (ARR): ₹${(pageNum * 4.2 + 65).toFixed(1)} करोड़ संस्थागत अनुबंधों के माध्यम से।
- शुद्ध राजस्व प्रतिधारण (NRR): ${(115 + (pageNum % 10)).toFixed(1)}% प्रमुख कॉर्पोरेट खातों में।
- सक्रिय दैनिक व्यावसायिक उपयोगकर्ता: ${users} उपयोगकर्ता विभिन्न राज्यों में।
- तकनीकी अवसंरचना विश्वसनीयता: 99.98% सिस्टम अपटाइम मानक।
- परिचालन नकदी प्रवाह: ₹${(pageNum * 1.5 + 12).toFixed(1)} करोड़ सकारात्मक नकदी प्रवाह।

३. आगामी लक्ष्य एवं क्रियान्वयन योजना:
प्रक्रियाओं का स्वचालन, क्लाउड आर्किटेक्चर का सुदृढ़ीकरण तथा स्थानीय वितरण नेटवर्क का विस्तार हमारी आगामी प्राथमिकताओं के केंद्र में रहेगा। सभी डेटा सुरक्षा ऑडिट और सूचना सुरक्षा प्रमाणपत्र सफलतापूर्वक पूर्ण किए जा चुके हैं।`;
}

const hindiPages = Array.from({ length: 20 }, (_, i) => generateHindiPage(i + 1)).join("\n\n");
const targetPath = path.join(fixturesDir, "20-page-hindi.txt");
fs.writeFileSync(targetPath, hindiPages, "utf8");
console.log(`Generated pure Hindi 20-page fixture at ${targetPath} (${hindiPages.length} chars).`);
